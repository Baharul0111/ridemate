"""Builds the Firebase Remote Config REST template and the APK-bundled defaults from config/remote_config/."""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any
from xml.sax.saxutils import escape

from .keys import ANDROID_ASSETS_CONFIG_DIR, ANDROID_DEFAULTS_XML, KEYS, KeySpec
from .validation import load_default, validate_key

_HTTPS_URL = re.compile(r"^https://[A-Za-z0-9.-]+(:[0-9]+)?(/[A-Za-z0-9._~/-]*)?$")
_SHA256_HEX = re.compile(r"^[0-9a-f]{64}$")
GENERATED_BY = "Generated by config/build_template.py from config/remote_config/. Do not edit by hand."


class BuildError(ValueError):
    pass


def phone_value(key: KeySpec, stored: Any) -> Any:
    """The value the phone reads: JSON keys are stored as the payload, scalars as {"value": ...}."""
    return stored if key.is_json else stored["value"]


def to_rc_string(key: KeySpec, value: Any) -> str:
    """Remote Config transports every value as a string; JSON is compact and keeps non-ASCII text as is."""
    if key.value_type == "JSON":
        return json.dumps(value, ensure_ascii=False, separators=(",", ":"))
    if key.value_type == "BOOLEAN":
        if not isinstance(value, bool):
            raise BuildError(f"{key.name}: expected a boolean")
        return "true" if value else "false"
    if key.value_type == "NUMBER":
        if isinstance(value, bool) or not isinstance(value, int | float):
            raise BuildError(f"{key.name}: expected a number")
        return str(value)
    return str(value)


def _validated_values(overrides: dict[str, Any] | None = None) -> dict[str, Any]:
    values: dict[str, Any] = {}
    problems: list[str] = []
    for key in KEYS:
        stored = load_default(key)
        if overrides and key.name in overrides:
            value = overrides[key.name]
            stored = value if key.is_json else {"value": value}
        problems += validate_key(key, stored)
        values[key.name] = phone_value(key, stored)
    if problems:
        raise BuildError("invalid config:\n  " + "\n  ".join(problems))
    return values


def build_template(api_base_url: str, owner_emails_sha256: list[str] | None = None) -> dict[str, Any]:
    """The REST template that `firebase deploy --only remoteconfig` publishes (api_base_url set)."""
    if not _HTTPS_URL.match(api_base_url):
        raise BuildError("--api-base-url must be an https URL without query or fragment")
    overrides: dict[str, Any] = {"api_base_url": api_base_url.rstrip("/")}
    if owner_emails_sha256:
        bad = [h for h in owner_emails_sha256 if not _SHA256_HEX.match(h)]
        if bad:
            raise BuildError(f"owner email hashes must be lower-case SHA-256 hex: {bad}")
        overrides["owner_emails_sha256"] = sorted(set(owner_emails_sha256))
    values = _validated_values(overrides)
    return {
        "parameters": {
            key.name: {
                "defaultValue": {"value": to_rc_string(key, values[key.name])},
                "valueType": key.value_type,
                "description": key.description,
            }
            for key in KEYS
        }
    }


def bundled_values() -> dict[str, Any]:
    values = _validated_values()
    for key in KEYS:
        if key.bundled_value is not None:
            values[key.name] = key.bundled_value
    return values


def bundled_outputs() -> dict[Path, str]:
    """Path → exact content of every APK-bundled default (assets/config/<key>.json per JSON key + XML)."""
    values = bundled_values()
    out: dict[Path, str] = {}
    for key in KEYS:
        if key.is_json:
            out[ANDROID_ASSETS_CONFIG_DIR / f"{key.name}.json"] = (
                json.dumps(values[key.name], ensure_ascii=False, indent=2) + "\n"
            )
    lines = ['<?xml version="1.0" encoding="utf-8"?>', f"<!-- {GENERATED_BY} -->", "<defaultsMap>"]
    for key in KEYS:
        lines += [
            "    <entry>",
            f"        <key>{key.name}</key>",
            f"        <value>{escape(to_rc_string(key, values[key.name]))}</value>",
            "    </entry>",
        ]
    lines.append("</defaultsMap>")
    out[ANDROID_DEFAULTS_XML] = "\n".join(lines) + "\n"
    return out


def stale_bundled_files() -> list[Path]:
    """Bundled files whose content on disk differs from what the builder would write."""
    return [
        path
        for path, content in bundled_outputs().items()
        if not path.exists() or path.read_text(encoding="utf-8") != content
    ]


def write_bundled() -> list[Path]:
    written: list[Path] = []
    expected = bundled_outputs()
    ANDROID_ASSETS_CONFIG_DIR.mkdir(parents=True, exist_ok=True)
    for stale in ANDROID_ASSETS_CONFIG_DIR.glob("*.json"):
        if stale not in expected:
            stale.unlink()
    for path, content in expected.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        written.append(path)
    return written


def write_template(template: dict[str, Any], out: Path) -> None:
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(template, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
